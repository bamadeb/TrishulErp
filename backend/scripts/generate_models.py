"""Generates SQLAlchemy models for every table from the SQL that defines the schema.

    uv run python scripts/generate_models.py           # write src/trishul_api/db/models/generated/
    uv run python scripts/generate_models.py --check   # CI: fail if the models are out of date

Sources, applied in order:
  1. database/01..07 and 12 (schema v3): CREATE TABLE and ALTER TABLE statements
  2. migrations/versions: the SQL in op.execute(...), following the revision chain
  3. database/11_descriptions.sql: table and column descriptions (docstrings)
  4. scripts/model_options.toml: audited tables, masked columns

Every column is mapped with its type, nullability and foreign key. Columns with a SQL Server
default (and ROWVERSION / computed columns) are server-generated, so INSERTs leave them out.
CHECK ([col] IN (N'a', N'b')) lists become Literal types. Tables with row_version get optimistic
locking (version_id_col).
"""

import ast
import json
import keyword
import re
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
DATABASE = BACKEND.parent / "database"
MIGRATIONS = BACKEND / "migrations" / "versions"
OUTPUT = BACKEND / "src" / "trishul_api" / "db" / "models" / "generated"
OPTIONS = Path(__file__).with_name("model_options.toml")

SCHEMA_SCRIPTS = [
    "01_core_setup.sql",
    "02_phase1_call_service.sql",
    "03_phase2_inventory.sql",
    "04_phase3_purchase_hr.sql",
    "05_phase4_sales.sql",
    "06_phase5_presales.sql",
    "07_phase6_presales_completion.sql",
    "12_gap_remediation.sql",
]
DESCRIPTION_SCRIPT = "11_descriptions.sql"
SCHEMAS = ["core", "svc", "inv", "pur", "sal", "pre", "hr", "acc", "int", "rpt"]
MODULE_NAMES = {"int": "int_"}  # `int` would shadow the builtin when imported as a module

# Names the generated module uses itself; a column with one of these names gets a "_" suffix.
RESERVED = {"metadata", "registry", "sa", "mssql", "dt", "uuid", "Decimal", "Literal", "Mapped"}
RESERVED |= {"mapped_column", "Audited", "Base", "str", "int", "bool", "bytes"}

HEADER = (
    "# Generated by backend/scripts/generate_models.py from database/*.sql and migrations/.\n"
    "# Do not edit: change the SQL (or scripts/model_options.toml) and re-run the generator.\n"
)


# ---------------------------------------------------------------- schema model


@dataclass
class Column:
    name: str
    sql_type: str
    args: str | None
    nullable: bool
    identity: bool = False
    primary_key: bool = False
    has_default: bool = False
    computed: str | None = None
    persisted: bool = False
    doc: str | None = None


@dataclass
class ForeignKey:
    column: str
    target: str  # schema.table.column


@dataclass
class Table:
    schema: str
    name: str
    doc: str | None = None
    columns: dict[str, Column] = field(default_factory=dict)
    checks: dict[str, str] = field(default_factory=dict)  # constraint name -> expression
    foreign_keys: dict[str, ForeignKey] = field(default_factory=dict)

    @property
    def key(self) -> str:
        return f"{self.schema}.{self.name}"


class SqlError(Exception):
    pass


# ---------------------------------------------------------------- SQL scanning helpers

STRING = re.compile(r"N?'(?:[^']|'')*'")


def strip_block_comments(sql: str) -> str:
    return re.sub(r"/\*.*?\*/", "", sql, flags=re.S)


def strip_line_comments(sql: str) -> str:
    """Removes -- comments outside string literals."""
    out, i, in_string = [], 0, False
    while i < len(sql):
        ch = sql[i]
        if in_string:
            out.append(ch)
            if ch == "'":
                if sql[i + 1 : i + 2] == "'":
                    out.append("'")
                    i += 1
                else:
                    in_string = False
        elif ch == "'":
            in_string = True
            out.append(ch)
        elif sql.startswith("--", i):
            while i < len(sql) and sql[i] != "\n":
                i += 1
            continue
        else:
            out.append(ch)
        i += 1
    return "".join(out)


def statement_end(sql: str, start: int) -> int:
    """Index just past the statement starting at `start`: its ';' at depth 0, or the end of the batch."""
    depth, i, in_string = 0, start, False
    while i < len(sql):
        ch = sql[i]
        if in_string:
            if ch == "'":
                if sql[i + 1 : i + 2] == "'":
                    i += 1
                else:
                    in_string = False
        elif ch == "'":
            in_string = True
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif ch == ";" and depth == 0:
            return i + 1
        i += 1
    return len(sql)


def balanced(text: str, open_index: int) -> tuple[str, int]:
    """The text inside the parenthesis at open_index, and the index after its closing ')'."""
    if text[open_index] != "(":
        raise SqlError(f"expected '(' in: {text[open_index : open_index + 60]}")
    depth, i, in_string = 0, open_index, False
    while i < len(text):
        ch = text[i]
        if in_string:
            if ch == "'":
                if text[i + 1 : i + 2] == "'":
                    i += 1
                else:
                    in_string = False
        elif ch == "'":
            in_string = True
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return text[open_index + 1 : i], i + 1
        i += 1
    raise SqlError(f"unbalanced parentheses in: {text[open_index : open_index + 60]}")


def split_top_level(text: str) -> list[str]:
    """Splits on commas outside parentheses and strings."""
    parts, depth, start, i, in_string = [], 0, 0, 0, False
    while i < len(text):
        ch = text[i]
        if in_string:
            if ch == "'":
                if text[i + 1 : i + 2] == "'":
                    i += 1
                else:
                    in_string = False
        elif ch == "'":
            in_string = True
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif ch == "," and depth == 0:
            parts.append(text[start:i])
            start = i + 1
        i += 1
    parts.append(text[start:])
    return [part.strip() for part in parts if part.strip()]


def unquote(value: str) -> str:
    return value.replace("''", "'")


def normalise(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


# ---------------------------------------------------------------- parsing


COLUMN_DEF = re.compile(r"^\[(\w+)\]\s+(.*)$", re.S)
TYPE_DEF = re.compile(r"(\w+)(?:\s*\(([^)]*)\))?")
CONSTRAINT_DEF = re.compile(r"^CONSTRAINT\s+\[(\w+)\]\s+(.*)$", re.S | re.I)
FOREIGN_KEY_DEF = re.compile(r"^FOREIGN KEY\s*\(\[(\w+)\]\)\s*REFERENCES\s*\[(\w+)\]\.\[(\w+)\]\s*\(\[(\w+)\]\)", re.I)


def parse_column(item: str) -> Column:
    match = COLUMN_DEF.match(item)
    if not match:
        raise SqlError(f"not a column definition: {item[:80]}")
    name, rest = match.group(1), match.group(2).strip()
    if rest.upper().startswith("AS"):
        expression, after = balanced(rest, rest.index("("))
        return Column(
            name, "COMPUTED", None, nullable=True, computed=normalise(expression), persisted="PERSISTED" in rest[after:]
        )
    type_match = TYPE_DEF.match(rest)
    if not type_match:
        raise SqlError(f"no type in: {item[:80]}")
    flags = STRING.sub("''", rest[type_match.end() :]).upper()
    return Column(
        name,
        type_match.group(1).upper(),
        type_match.group(2).replace(" ", "") if type_match.group(2) else None,
        nullable=not re.search(r"\bNOT\s+NULL\b", flags),
        identity="IDENTITY" in flags,
        primary_key="PRIMARY KEY" in flags,
        has_default=bool(re.search(r"\bDEFAULT\b", flags)),
    )


def apply_constraint(table: Table, item: str) -> None:
    match = CONSTRAINT_DEF.match(item)
    if not match:
        raise SqlError(f"not a constraint: {item[:80]}")
    name, body = match.group(1), match.group(2).strip()
    upper = body.upper()
    if upper.startswith("CHECK"):
        expression, _ = balanced(body, body.index("("))
        table.checks[name] = normalise(expression)
    elif upper.startswith("FOREIGN KEY"):
        fk = FOREIGN_KEY_DEF.match(body)
        if not fk:
            raise SqlError(f"unsupported foreign key on {table.key}: {body[:100]}")
        column, schema, target, target_column = fk.groups()
        table.foreign_keys[name] = ForeignKey(column, f"{schema}.{target}.{target_column}")
    elif upper.startswith("DEFAULT"):
        target = re.search(r"\bFOR\s+\[(\w+)\]", body, re.I)
        if not target:
            raise SqlError(f"unsupported default on {table.key}: {body[:100]}")
        table.columns[target.group(1)].has_default = True
    elif upper.startswith(("PRIMARY KEY", "UNIQUE")):
        pass  # the id primary key is declared on the column; unique rules don't change the mapping
    else:
        raise SqlError(f"unsupported constraint on {table.key}: {body[:100]}")


def parse_items(table: Table, items: list[str]) -> None:
    for item in items:
        if item.upper().startswith("CONSTRAINT"):
            apply_constraint(table, item)
        elif item.startswith("["):
            column = parse_column(item)
            table.columns[column.name] = column
        elif item.upper().startswith(("PRIMARY KEY", "INDEX", "UNIQUE")):
            pass
        else:
            raise SqlError(f"unsupported item in {table.key}: {item[:80]}")


STATEMENT = re.compile(r"\b(CREATE\s+TABLE|ALTER\s+TABLE)\s+\[(\w+)\]\.\[(\w+)\]", re.I)


def table_comment(batch: str, start: int) -> str | None:
    """The '-- ...' lines right above a CREATE TABLE (an IF guard line may sit in between)."""
    lines = batch[:start].rstrip().splitlines()
    comment: list[str] = []
    for line in reversed(lines):
        stripped = line.strip()
        if stripped.startswith("--"):
            comment.insert(0, stripped.lstrip("-").strip())
        elif stripped.upper().startswith("IF ") and not comment:
            continue
        else:
            break
    return " ".join(comment) or None


def apply_sql(tables: dict[str, Table], sql: str, source: str) -> None:
    sql = strip_block_comments(sql)
    for batch in re.split(r"^\s*GO\s*$", sql, flags=re.M | re.I):
        position = 0
        clean = strip_line_comments(batch)
        # Statements are found in the comment-free text; comments for docs come from the original.
        while match := STATEMENT.search(clean, position):
            end = statement_end(clean, match.start())
            statement = clean[match.end() : end].rstrip(";").strip()
            kind, schema, name = normalise(match.group(1)).upper(), match.group(2), match.group(3)
            key = f"{schema}.{name}"
            try:
                if kind == "CREATE TABLE":
                    body, _ = balanced(statement, statement.index("("))
                    original = re.search(rf"CREATE\s+TABLE\s+\[{schema}\]\.\[{name}\]", batch, re.I)
                    table = Table(schema, name, doc=table_comment(batch, original.start()) if original else None)
                    parse_items(table, split_top_level(body))
                    tables[key] = table
                else:
                    apply_alter(tables[key], statement)
            except (SqlError, KeyError, ValueError) as exc:
                raise SqlError(f"{source}: {key}: {exc}") from exc
            position = end


def apply_alter(table: Table, statement: str) -> None:
    upper = statement.upper()
    if upper.startswith("ADD"):
        parse_items(table, split_top_level(statement[3:]))
    elif upper.startswith("ALTER COLUMN"):
        changed = parse_column(statement[len("ALTER COLUMN") :].strip())
        existing = table.columns[changed.name]
        existing.sql_type, existing.args, existing.nullable = changed.sql_type, changed.args, changed.nullable
    elif upper.startswith("DROP CONSTRAINT"):
        for name in re.findall(r"\[(\w+)\]", statement):
            table.checks.pop(name, None)
            table.foreign_keys.pop(name, None)
    elif upper.startswith("DROP COLUMN"):
        for name in re.findall(r"\[(\w+)\]", statement):
            table.columns.pop(name)
    else:
        raise SqlError(f"unsupported ALTER: {statement[:80]}")


DESCRIPTION = re.compile(
    r"sp_addextendedproperty\s+N'MS_Description',\s*N'((?:[^']|'')*)',\s*N'SCHEMA',\s*N'(\w+)',"
    r"\s*N'TABLE',\s*N'(\w+)'(?:,\s*N'COLUMN',\s*N'(\w+)')?",
    re.S,
)


def apply_descriptions(tables: dict[str, Table], sql: str) -> None:
    for text, schema, name, column in DESCRIPTION.findall(sql):
        table = tables.get(f"{schema}.{name}")
        if table is None:
            continue
        if column:
            if column in table.columns:
                table.columns[column].doc = unquote(text)
        else:
            table.doc = unquote(text)


def migration_sql() -> list[tuple[str, str]]:
    """SQL from op.execute("...") in each Alembic revision, oldest first."""
    revisions: dict[str, tuple[str | None, Path]] = {}
    for path in MIGRATIONS.glob("*.py"):
        module = ast.parse(path.read_text(encoding="utf-8"))
        values = {
            node.targets[0].id: node.value.value
            for node in module.body
            if isinstance(node, ast.Assign)
            and isinstance(node.targets[0], ast.Name)
            and isinstance(node.value, ast.Constant)
        }
        down_revision = values.get("down_revision")
        revisions[str(values["revision"])] = (None if down_revision is None else str(down_revision), path)
    children = {down: rev for rev, (down, _) in revisions.items()}
    ordered, current = [], children.get(None)
    while current is not None:
        ordered.append(revisions[current][1])
        current = children.get(current)
    result = []
    for path in ordered:
        upgrade = next(
            node
            for node in ast.parse(path.read_text(encoding="utf-8")).body
            if isinstance(node, ast.FunctionDef) and node.name == "upgrade"
        )
        for node in ast.walk(upgrade):
            if (
                isinstance(node, ast.Call)
                and getattr(node.func, "attr", None) == "execute"
                and node.args
                and isinstance(node.args[0], ast.Constant)
            ):
                result.append((path.name, str(node.args[0].value)))
    return result


def load_schema() -> dict[str, Table]:
    tables: dict[str, Table] = {}
    for script in SCHEMA_SCRIPTS:
        apply_sql(tables, (DATABASE / script).read_text(encoding="utf-8"), script)
    migrations = migration_sql()
    for source, sql in migrations:
        apply_sql(tables, sql, source)
    apply_descriptions(tables, (DATABASE / DESCRIPTION_SCRIPT).read_text(encoding="utf-8"))
    for _, sql in migrations:
        apply_descriptions(tables, sql)
    return tables


# ---------------------------------------------------------------- code generation


def q(text: str) -> str:
    """A double-quoted Python string literal."""
    return json.dumps(text, ensure_ascii=False)


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def enum_values(expression: str) -> tuple[str, list[str]] | None:
    """(column, values) for CHECK ([col] IN (N'a', ...)), optionally with 'IS NULL OR'."""
    text = expression
    while text.startswith("(") and balanced(text, 0)[1] == len(text):
        text = balanced(text, 0)[0].strip()
    match = re.fullmatch(r"(?:\[(\w+)\] IS NULL OR )?\[(\w+)\] IN \((.*)\)", text)
    if not match or (match.group(1) and match.group(1) != match.group(2)):
        return None
    items = split_top_level(match.group(3))
    if not all(re.fullmatch(r"N'(?:[^']|'')*'", item) for item in items):
        return None
    return match.group(2), [unquote(item[2:-1]) for item in items]


def column_type(column: Column, table: Table) -> tuple[str, str]:
    """(SQLAlchemy type expression, Python type) for a column."""
    t, args = column.sql_type, column.args
    if t == "COMPUTED":
        assert column.computed is not None
        source = re.findall(r"\[(\w+)\]", column.computed)
        return column_type(table.columns[source[0]], table)
    simple = {
        "BIGINT": ("sa.BigInteger()", "int"),
        "INT": ("sa.Integer()", "int"),
        "SMALLINT": ("sa.SmallInteger()", "int"),
        "TINYINT": ("mssql.TINYINT()", "int"),
        "BIT": ("sa.Boolean()", "bool"),
        "DATE": ("sa.Date()", "dt.date"),
        "UNIQUEIDENTIFIER": ("sa.Uuid()", "uuid.UUID"),
        "ROWVERSION": ("mssql.ROWVERSION()", "bytes"),
    }
    if t in simple:
        return simple[t]
    if t == "NVARCHAR":
        return ("sa.UnicodeText()", "str") if args == "MAX" else (f"sa.NVARCHAR({args})", "str")
    if t == "CHAR":
        return f"sa.CHAR({args})", "str"
    if t == "DECIMAL":
        precision, scale = (args or "18,0").split(",")
        return f"sa.Numeric({precision}, {scale})", "Decimal"
    if t == "DATETIME2":
        return f"mssql.DATETIME2({args or 7})", "dt.datetime"
    if t == "TIME":
        return f"mssql.TIME({args or 7})", "dt.time"
    raise SqlError(f"{table.key}.{column.name}: unsupported type {t}")


def attribute_name(column: str) -> str:
    return f"{column}_" if keyword.iskeyword(column) or column in RESERVED else column


@dataclass
class Options:
    audited: set[str]
    masked: dict[str, list[str]]


def load_options(tables: dict[str, Table]) -> Options:
    raw = tomllib.loads(OPTIONS.read_text(encoding="utf-8"))
    options = Options(audited=set(raw.get("audited", [])), masked=raw.get("masked", {}))
    for key in options.audited | set(options.masked):
        if key not in tables:
            raise SqlError(f"model_options.toml: unknown table {key}")
    for key, columns in options.masked.items():
        for column in columns:
            if column not in tables[key].columns:
                raise SqlError(f"model_options.toml: unknown column {key}.{column}")
    return options


def render_table(table: Table, options: Options, enums: dict[str, str]) -> list[str]:
    class_name = pascal(table.name)
    audited = table.key in options.audited
    lines = [f"class {class_name}({'Audited, ' if audited else ''}Base):"]
    lines.append(f"    {python_docstring(table.doc or f'{table.key}')}")
    lines.append("")
    lines.append(f"    __tablename__ = {q(table.name)}")
    lines.append(f'    __table_args__ = {{"schema": {q(table.schema)}}}')
    if table.key in options.masked:
        masked = ", ".join(q(c) for c in sorted(options.masked[table.key]))
        lines.append(f"    __audit_masked__ = frozenset({{{masked}}})")
    lines.append("")
    foreign_keys = {fk.column: fk.target for fk in table.foreign_keys.values()}
    for column in table.columns.values():
        sa_type, py_type = column_type(column, table)
        py_type = enums.get(column.name, py_type)
        nullable = column.nullable and not column.primary_key
        annotation = f"Mapped[{py_type}{' | None' if nullable else ''}]"
        args = [sa_type]
        if column.name in foreign_keys:
            args.append(f'sa.ForeignKey("{foreign_keys[column.name]}")')
        if column.computed:
            persisted = ", persisted=True" if column.persisted else ""
            args.append(f"sa.Computed({q(column.computed)}{persisted})")
        if column.primary_key:
            args.append("primary_key=True")
        if column.sql_type == "ROWVERSION":
            args.append("server_default=sa.FetchedValue(), server_onupdate=sa.FetchedValue()")
        elif column.has_default:
            args.append("server_default=sa.FetchedValue()")
        attribute = attribute_name(column.name)
        if attribute != column.name:
            args.insert(0, q(column.name))
        doc = column.doc
        if doc and column.name in enums:
            # Descriptions list the v2 values ("Allowed: ..."); the Literal type is the current list.
            doc = re.sub(r"\s*Allowed:.*$", "", doc, flags=re.S)
        if doc:
            args.append(f"doc={q(doc)}")
        lines.append(f"    {attribute}: {annotation} = mapped_column({', '.join(args)})")
    if "row_version" in table.columns:
        lines.append("")
        lines.append('    __mapper_args__ = {"version_id_col": row_version, "version_id_generator": False}')
    return lines


def python_docstring(text: str) -> str:
    return '"""' + text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"') + '"""'


def render_module(schema: str, tables: list[Table], options: Options) -> tuple[str, list[str]]:
    body: list[str] = []
    aliases: list[str] = []
    exported: list[str] = []
    for table in tables:
        enums: dict[str, str] = {}
        for expression in table.checks.values():
            found = enum_values(expression)
            if found and found[0] in table.columns and table.columns[found[0]].sql_type in ("NVARCHAR", "CHAR"):
                column, values = found
                alias = f"{pascal(table.name)}{pascal(column)}"
                enums[column] = alias
                listed = ", ".join(q(v) for v in values)
                aliases.append(f"{alias} = Literal[{listed}]")
                exported.append(alias)
        body.append("")
        body.append("")
        body.extend(render_table(table, options, enums))
        exported.append(pascal(table.name))
    text = "\n".join(body)
    imports = ["import datetime as dt  # noqa: F401", "import uuid  # noqa: F401"]
    imports += ["from decimal import Decimal  # noqa: F401", "from typing import Literal  # noqa: F401", ""]
    imports += ["import sqlalchemy as sa", "from sqlalchemy.dialects import mssql  # noqa: F401"]
    imports += ["from sqlalchemy.orm import Mapped, mapped_column", ""]
    uses_audited = "(Audited, Base)" in text
    imports.append(f"from trishul_api.db.models.base import {'Audited, ' if uses_audited else ''}Base")
    doc = f'"""ORM models for the {schema} schema: {len(tables)} tables."""'
    alias_block = "\n" + "\n".join(aliases) + "\n" if aliases else ""
    module = f"{HEADER}\n{doc}\n\n" + "\n".join(imports) + "\n" + alias_block + text + "\n"
    return module, exported


def generate() -> dict[Path, str]:
    tables = load_schema()
    options = load_options(tables)
    files: dict[Path, str] = {}
    init_imports: list[str] = []
    all_names: list[str] = []
    class_owner: dict[str, str] = {}
    for schema in SCHEMAS:
        schema_tables = [t for t in tables.values() if t.schema == schema]
        if not schema_tables:
            continue
        module_name = MODULE_NAMES.get(schema, schema)
        text, exported = render_module(schema, schema_tables, options)
        for name in exported:
            if name in class_owner:
                raise SqlError(f"name {name} is generated for both {class_owner[name]} and {schema}")
            class_owner[name] = schema
        files[OUTPUT / f"{module_name}.py"] = text
        names = ",\n".join(f"    {name}" for name in exported)
        init_imports.append(f"from trishul_api.db.models.generated.{module_name} import (\n{names},\n)")
        all_names += exported
    unknown = set(tables) - {t.key for t in tables.values() if t.schema in SCHEMAS}
    if unknown:
        raise SqlError(f"tables in schemas the generator doesn't know: {sorted(unknown)}")
    listed = "\n".join(f'    "{name}",' for name in sorted(all_names))
    files[OUTPUT / "__init__.py"] = (
        f'{HEADER}\n"""ORM models for all {len(tables)} tables."""\n\n'
        + "\n".join(init_imports)
        + f"\n\n__all__ = [\n{listed}\n]\n"
    )
    return files


def main() -> int:
    try:
        files = generate()
    except SqlError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if "--check" in sys.argv:
        stale = [path for path, text in files.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
        extra = [p for p in OUTPUT.glob("*.py") if p not in files] if OUTPUT.exists() else []
        if stale or extra:
            for path in stale + extra:
                print(f"out of date: {path.relative_to(BACKEND)}")
            print("Run: uv run python scripts/generate_models.py")
            return 1
        print(f"Models are up to date ({len(files) - 1} modules).")
        return 0
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for path in OUTPUT.glob("*.py"):
        if path not in files:
            path.unlink()
    for path, text in files.items():
        path.write_text(text, encoding="utf-8", newline="\n")
    tables = sum(text.count("\nclass ") for path, text in files.items() if path.name != "__init__.py")
    print(f"Wrote {len(files) - 1} modules with {tables} models to {OUTPUT.relative_to(BACKEND)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
